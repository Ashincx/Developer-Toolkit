/**
 * Export Generators: Standalone SVG, HTML+CSS, React JSX, JSON Project
 */
import { generateStylesCSS } from './animationPresets';

/**
 * Builds a 100% self-contained standalone animated SVG
 */
export function buildStandaloneSvg(svgString, animations) {
  if (!svgString) return '';

  const css = generateStylesCSS(animations, {
    scopeSelector: '',
    speed: 1,
    isScrubbing: false,
    includeReducedMotion: true
  });

  const styleTag = `<style>\n${css.trim()}\n</style>`;

  // Insert <style> tag immediately after opening <svg ...>
  const svgOpenTagMatch = svgString.match(/<svg[^>]*>/i);
  if (!svgOpenTagMatch) {
    return svgString;
  }

  const openTag = svgOpenTagMatch[0];
  const rest = svgString.slice(openTag.length);

  return `${openTag}\n  ${styleTag}\n${rest}`;
}

/**
 * Builds HTML + CSS snippet
 */
export function buildHtmlCss(svgString, animations) {
  const css = generateStylesCSS(animations, {
    scopeSelector: '.animated-svg-container',
    speed: 1,
    isScrubbing: false,
    includeReducedMotion: true
  });

  return `<!-- HTML & CSS Animated SVG -->
<div class="animated-svg-container">
  ${svgString.trim()}
</div>

<style>
.animated-svg-container {
  display: inline-flex;
  align-items: center;
  justify-content: center;
  width: 100%;
  max-width: 400px;
}

${css.trim()}
</style>`;
}

/**
 * Converts standard HTML/SVG attributes to camelCase React JSX attributes
 */
function toReactJsx(svgString) {
  const attrMap = {
    'class': 'className',
    'viewbox': 'viewBox',
    'stroke-width': 'strokeWidth',
    'stroke-linecap': 'strokeLinecap',
    'stroke-linejoin': 'strokeLinejoin',
    'stroke-dasharray': 'strokeDasharray',
    'stroke-dashoffset': 'strokeDashoffset',
    'stroke-miterlimit': 'strokeMiterlimit',
    'clip-path': 'clipPath',
    'fill-rule': 'fillRule',
    'clip-rule': 'clipRule',
    'stop-color': 'stopColor',
    'stop-opacity': 'stopOpacity',
    'font-family': 'fontFamily',
    'font-size': 'fontSize',
    'font-weight': 'fontWeight',
    'text-anchor': 'textAnchor',
    'dominant-baseline': 'dominantBaseline',
    'xlink:href': 'xlinkHref',
    'xmlns:xlink': 'xmlnsXlink'
  };

  let jsx = svgString;

  // Replace hyphenated and case-sensitive SVG attributes
  Object.entries(attrMap).forEach(([htmlAttr, reactAttr]) => {
    const regex = new RegExp(`\\b${htmlAttr}=`, 'gi');
    jsx = jsx.replace(regex, `${reactAttr}=`);
  });

  return jsx;
}

/**
 * Builds a complete React JSX component
 */
export function buildReactJsx(svgString, animations, componentName = 'AnimatedSvg') {
  const css = generateStylesCSS(animations, {
    scopeSelector: '.animated-svg-wrapper',
    speed: 1,
    isScrubbing: false,
    includeReducedMotion: true
  });

  const jsxSvg = toReactJsx(svgString.trim());

  return `import React from 'react';

/**
 * ${componentName} - Generated by Developer Toolkit SVG Animation Creator
 */
export default function ${componentName}({ className = '', style = {}, ...props }) {
  return (
    <div className={\`animated-svg-wrapper \${className}\`} style={{ display: 'inline-block', ...style }} {...props}>
      <style>{\`
${css.trim()}
      \`}</style>
      ${jsxSvg}
    </div>
  );
}
`;
}

/**
 * Builds project JSON file for saving and reloading
 */
export function buildProjectJson(data) {
  return JSON.stringify(
    {
      toolkitVersion: '1.0.0',
      type: 'developer-toolkit-svg-animation',
      name: data.name || 'Untitled SVG Animation',
      exportedAt: new Date().toISOString(),
      svgString: data.svgString,
      animations: data.animations,
      layers: data.layers,
      canvasSettings: data.canvasSettings
    },
    null,
    2
  );
}

/**
 * Validates and parses uploaded JSON project
 */
export function parseProjectJson(jsonString) {
  try {
    const data = JSON.parse(jsonString);
    if (!data.svgString || !data.animations) {
      throw new Error('Missing essential svgString or animations in JSON project file.');
    }
    return {
      ok: true,
      data
    };
  } catch (err) {
    return {
      ok: false,
      error: err.message
    };
  }
}
